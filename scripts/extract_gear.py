def normalize_talent(raw):
    if not raw:
        return None
    key = raw.lower().strip()
    mapped = TALENT_MAP.get(key)
    if mapped and mapped in VALID_TALENT_IDS:
        return mapped
    # Try partial match
    for k, v in TALENT_MAP.items():
        if k in key and v in VALID_TALENT_IDS:
            return v
    return None

# ---------------------------------------------------------------------------
# Reach class normalization
# ---------------------------------------------------------------------------
def normalize_reach(raw):
    if not raw:
        return "medium"
    r = raw.lower().strip()
    if "kurz" in r or "short" in r or r in ("k", "s"):
        return "short"
    if "lang" in r or "long" in r or r in ("l",):
        return "long"
    if "sehr lang" in r or "very long" in r:
        return "very_long"
    return "medium"

# ---------------------------------------------------------------------------
# Damage normalization
# ---------------------------------------------------------------------------
def normalize_damage(raw):
    if not raw:
        return "1d6"
    raw = raw.strip()
    # Already looks like dice expression
    if re.match(r"\d+d\d+", raw, re.I):
        return raw
    # German TP notation: "1W6+2" -> "1d6+2"
    cleaned = re.sub(r"(\d+)[Ww](\d+)", r"\1d\2", raw)
    return cleaned or raw

# ---------------------------------------------------------------------------
# Number helpers
# ---------------------------------------------------------------------------
def to_int(raw, default=0):
    if raw is None:
        return default
    try:
        return int(str(raw).strip().replace("−", "-").replace("–", "-"))
    except (ValueError, TypeError):
        return default

def to_float(raw, default=0.0):
    if raw is None:
        return default
    try:
        s = str(raw).strip().replace(",", ".").replace("−", "-").replace("–", "-")
        return float(s)
    except (ValueError, TypeError):
        return default

# ---------------------------------------------------------------------------
# Slug / ID helpers
# ---------------------------------------------------------------------------
def slugify(name):
    s = name.lower().strip()
    s = re.sub(r"[^\w\s]", "", s)
    s = re.sub(r"\s+", "_", s)
    s = s.strip("_")
    return s

