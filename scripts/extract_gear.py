def validate_weapons(weapons):
    errors = []
    ids_seen = set()
    for w in weapons:
        wid = w["id"]
        if wid in ids_seen:
            errors.append(f"Duplicate weapon id: {wid!r}")
        ids_seen.add(wid)
        ct = w.get("combat_talent")
        if ct and ct not in VALID_TALENT_IDS:
            errors.append(f"Weapon {wid!r}: invalid combat_talent {ct!r}")
        for st in w.get("secondary_talents", []):
            if st not in VALID_TALENT_IDS:
                errors.append(f"Weapon {wid!r}: invalid secondary_talent {st!r}")
    return errors

def validate_armor(armors):
    errors = []
    ids_seen = set()
    for a in armors:
        aid = a["id"]
        if aid in ids_seen:
            errors.append(f"Duplicate armor id: {aid!r}")
        ids_seen.add(aid)
    return errors

