# ---------------------------------------------------------------------------
# Resolve PDF paths from TDE4_PDF_reference.txt
# ---------------------------------------------------------------------------
ROOT = Path(__file__).parent.parent
REF_FILE = ROOT / "TDE4_PDF_reference.txt"

def load_pdf_paths():
    paths = {}
    with open(REF_FILE, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                alias, _, rest = line.partition("=")
                alias = alias.strip()
                path = rest.strip().strip('"')
                paths[alias] = path
    return paths

PDF_PATHS = load_pdf_paths()

def open_pdf(alias):
    path = PDF_PATHS.get(alias)
    if not path or not os.path.exists(path):
        print(f"  WARNING: PDF '{alias}' not found at {path!r} — skipping")
        return None
    return pdfplumber.open(path)

